class Approval:
    def __init__(self, world: World) -> None:
        self.world = world
        self.directory = world.tmp / "curator"
        self.curator = Curator(self.directory, "curator")
        review_value, ok = world.review()
        assert ok
        self.review_value = review_value
        self.review = self.directory / "review.json"
        self.review.write_bytes(canonical(review_value))
        self.value = approval_value(review_value)

    def write(self, value=None, *, signer=None, raw=None) -> tuple[Path, Path]:
        body = (
            raw
            if raw is not None
            else json.dumps(value or self.value, indent=2, sort_keys=True).encode()
            + b"\n"
        )
        approval = self.directory / "approval.json"
        approval.write_bytes(body)
        signature = (signer or self.curator).sign(body, self.directory / "approval.sig")
        return approval, signature

    def check(
        self,
        *,
        approval=None,
        signature=None,
        review=None,
        public=None,
        pin=None,
        openssl=None,
    ):
        if approval is None or signature is None:
            approval, signature = self.write()
        store, checkout = self.world.open()
        with store:
            return EVIDENCE.check_approval(
                store=store,
                checkout=checkout,
                review_raw=(review or self.review).read_bytes(),
                approval_raw=approval.read_bytes(),
                signature=signature.read_bytes(),
                public_key_raw=(public or self.curator.public).read_bytes(),
                curator_signing_key_sha256=pin or self.curator.key_sha256,
                openssl=Path(openssl or OPENSSL_BIN),
            )

    def arguments(self, approval: Path, signature: Path) -> list[str]:
        return [
            "check-approval",
            "--store",
            str(self.world.store),
            "--checkout",
            str(self.world.checkout),
            "--review",
            str(self.review),
            "--approval",
            str(approval),
            "--signature",
            str(signature),
            "--curator-public-key",
            str(self.curator.public),
            "--curator-signing-key-sha256",
            self.curator.key_sha256,
            "--openssl",
            OPENSSL_BIN,
        ]


