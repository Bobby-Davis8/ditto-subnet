def observed_for(expect: dict) -> dict:
    kind = expect["type"]
    if kind == "outcome_in":
        return {"outcome": expect["accept"][0]}
    if kind == "exact":
        return copy.deepcopy(expect["value"])
    if kind == "profile_equal":
        return {"cgroup": 536870912, "profile": 536870912}
    if kind == "bounded":
        return {"enforced": True, "limit": 1000, "measured": 1000}
    if kind == "supervisor_timeout":
        return {
            "deadline_ms": 5000,
            "elapsed_ms": 5200,
            "exit_code": 124,
            "live_processes": 0,
        }
    if kind == "tests":
        if expect["result"] == "all_pass":
            return {"passed": 3, "total": 3}
        return {"passed": 1, "total": 3}
    assert kind == "subordinate_uid"
    return {"host_uid": SUBORDINATE["uid_start"] + 65531}


def build_record(kind: str, *, tools: dict, pre_sha: str, started: int) -> dict:
    entry = catalog()["kinds"][kind]
    endpoints = ENDPOINTS if kind == "network_enforcement" else []
    trusted = [
        item["endpoint_sha256"] for item in endpoints if item["role"] == "trusted"
    ]
    phases = []
    moment = started
    for phase in entry["phases"]:
        probes = []
        for probe in entry["probes"]:
            if probe["phase"] != phase:
                continue
            scopes: list[tuple[str | None, str | None]]
            if probe["scope"] == "host":
                scopes = [(None, None)]
            elif probe["scope"] == "language":
                scopes = [(language, None) for language in EVIDENCE.LANGUAGES]
            else:
                scopes = [(None, endpoint) for endpoint in trusted]
            for language, endpoint in scopes:
                probes.append(
                    {
                        "id": probe["id"],
                        "language": language,
                        "endpoint_sha256": endpoint,
                        "expect": copy.deepcopy(probe["expect"]),
                        "observed": observed_for(probe["expect"]),
                        "matched": True,
                    }
                )
        probes.sort(
            key=lambda item: (
                item["id"],
                item["language"] or "",
                item["endpoint_sha256"] or "",
            )
        )
        phases.append(
            {
                "name": phase,
                "started_at_unix": moment + 1,
                "completed_at_unix": moment + 2,
                "probes": probes,
            }
        )
        moment += 2
    return {
        "schema": EVIDENCE.RECORD_SCHEMA,
        "kind": kind,
        "coverage": "same_boot",
        "not_covered": ["daemon_restart_recovery", "reboot_recovery"],
        "tolerances_version": EVIDENCE.TOLERANCES["version"],
        "host": {
            "machine_id_sha256": MACHINE,
            "boot_id": BOOT,
            "kernel_release": KERNEL,
            "daemon_identity_sha256": DAEMON,
            "subordinate_ids": dict(SUBORDINATE),
            "router_namespace": "rootless-netns",
        },
        "release": {
            "source_revision": REVISION,
            "release_manifest_sha256": MANIFEST,
            "runtime_archive_sha256": RUNTIME,
            "image_approval_sha256": dict(IMAGES),
        },
        "pre_collection_preflight_sha256": pre_sha,
        "inputs": {name: digest(name) for name in entry["inputs"]},
        "endpoints": copy.deepcopy(endpoints),
        "tools": dict(tools),
        "preconditions": dict(EVIDENCE.PRECONDITIONS),
        "phases": phases,
        "residue": dict(EVIDENCE.RESIDUE),
        "started_at_unix": started,
        "completed_at_unix": moment + 1,
    }


