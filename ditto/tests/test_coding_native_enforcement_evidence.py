@needs_openssl
def test_curator_verification_is_pure_ed25519():
    # RFC 8032 section 7.1, TEST 2.
    key = bytes.fromhex(
        "3d4017c3e843895a92b70aa74d1b7ebc9c982ccf2ec4968cc0cd55f12af4660c"
    )
    signature = bytes.fromhex(
        "92a009a9f0d4cab8720e820b5f642540a2b27b5416503f8fb3762223ebdb69da"
        "085ac1e43e15996e458f3613d0f11d8c387b2eaeb4302aeeb00d291612bb0c00"
    )
    EVIDENCE.verify_ed25519(Path(OPENSSL_BIN), key, b"\x72", signature)
    with pytest.raises(EVIDENCE.Refusal, match="does not verify"):
        EVIDENCE.verify_ed25519(Path(OPENSSL_BIN), key, b"\x73", signature)
    # S + L is the same point equation but a non-canonical encoding.
    order = 2**252 + 27742317777372353535851937790883648493
    s = int.from_bytes(signature[32:], "little") + order
    malleated = signature[:32] + s.to_bytes(32, "little")
    with pytest.raises(EVIDENCE.Refusal, match="does not verify"):
        EVIDENCE.verify_ed25519(Path(OPENSSL_BIN), key, b"\x72", malleated)


