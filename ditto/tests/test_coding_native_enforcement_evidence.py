def test_store_recovers_a_crash_between_link_and_unlink(world, monkeypatch):
    raw = b'{"interrupted":true}'
    sha = hashlib.sha256(raw).hexdigest()
    monkeypatch.setattr(EVIDENCE, "_rename_noreplace", lambda *_args: None)
    real_unlink = os.unlink

    def crash(path, *args, **kwargs):
        if str(path).startswith(".partial-"):
            raise KeyboardInterrupt("simulated crash")
        return real_unlink(path, *args, **kwargs)

    monkeypatch.setattr(EVIDENCE.os, "unlink", crash)
    with EVIDENCE.Store(world.store) as store, pytest.raises(KeyboardInterrupt):
        store.put(raw)
    monkeypatch.setattr(EVIDENCE.os, "unlink", real_unlink)
    assert (world.store / sha).stat().st_nlink == 2
    with EVIDENCE.Store(world.store) as store:
        assert store.get(sha) == raw
    assert (world.store / sha).stat().st_nlink == 1
    assert not [path for path in world.store.iterdir() if path.name.startswith(".")]

    # A second link that is not our partial is never removed.
    other = world.put(b'{"foreign":true}')
    os.link(world.store / other, world.tmp / "foreign-link")
    with (
        EVIDENCE.Store(world.store) as store,
        pytest.raises(EVIDENCE.Refusal, match="private single-link"),
    ):
        store.get(other)
    assert (world.tmp / "foreign-link").exists()


