def test_retain_writes_exclusive_private_objects(world, capsys):
    source = world.tmp / "record.json"
    raw = canonical(world.records["cleanup_recovery"])
    source.write_bytes(raw)
    code = EVIDENCE.main(
        [
            "retain",
            "--store",
            str(world.store),
            "--type",
            "record",
            "--input",
            str(source),
        ]
    )
    output = json.loads(capsys.readouterr().out)
    assert code == 0
    assert output == {
        "retained_sha256": hashlib.sha256(raw).hexdigest(),
        "type": "record",
    }
    stored = world.store / output["retained_sha256"]
    assert stat.S_IMODE(stored.stat().st_mode) == 0o400
    assert sorted(path.name for path in world.store.iterdir()) == sorted(
        [world.pre_sha, output["retained_sha256"]]
    )
    with EVIDENCE.Store(world.store) as store:
        assert store.get(output["retained_sha256"]) == raw
        with pytest.raises(EVIDENCE.Refusal, match="already retained"):
            store.put(raw)
    assert not [path for path in world.store.iterdir() if path.name.startswith(".")]


