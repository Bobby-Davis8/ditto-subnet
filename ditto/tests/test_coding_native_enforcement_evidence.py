def set_path(*path, value):
    def change(record):
        target = record
        for key in path[:-1]:
            target = target[key]
        target[path[-1]] = copy.deepcopy(value)

    return change


def drop_probe(probe_id, endpoint=None):
    def change(record):
        for phase in record["phases"]:
            phase["probes"] = [
                p
                for p in phase["probes"]
                if (p["id"], p["endpoint_sha256"]) != (probe_id, endpoint)
            ]

    return change


def edit_probe(probe_id, endpoint=None, language=None, **fields):
    def change(record):
        find_probe(record, probe_id, language, endpoint).update(copy.deepcopy(fields))

    return change


def edit_observed(probe_id, language, **fields):
    def change(record):
        find_probe(record, probe_id, language)["observed"].update(fields)

    return change


def add_cleanup_probe(record):
    phase = record["phases"][0]
    extra = copy.deepcopy(phase["probes"][0])
    extra["id"] = "cleanup.reboot.absent"
    phase["probes"].append(extra)


def repeat_probe(record):
    phase = record["phases"][0]
    phase["probes"].append(copy.deepcopy(phase["probes"][0]))


def move_probe(record):
    moved = record["phases"][0]["probes"].pop()
    record["phases"][1]["probes"].append(moved)
    record["phases"][1]["probes"].sort(key=lambda p: p["id"])


def reverse_probes(record):
    record["phases"][0]["probes"].reverse()


def swap_phases(record):
    record["phases"][0], record["phases"][1] = record["phases"][1], record["phases"][0]


def unsort_endpoints(record):
    record["endpoints"].reverse()


def drop_trusted_endpoint(record):
    # List one trusted endpoint and drop the probes of the other: a record that
    # self-declares a smaller trusted set.
    record["endpoints"] = [
        item for item in record["endpoints"] if item["endpoint_sha256"] != TRUSTED[1]
    ]
    for phase in record["phases"]:
        phase["probes"] = [
            p for p in phase["probes"] if p["endpoint_sha256"] != TRUSTED[1]
        ]


def replace_router(record):
    for item in record["endpoints"]:
        if item["role"] == "router":
            item["endpoint_sha256"] = digest("unlisted-router")
    record["endpoints"].sort(key=lambda item: (item["role"], item["endpoint_sha256"]))


