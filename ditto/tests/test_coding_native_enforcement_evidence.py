def shifted(record: dict, started: int) -> dict:
    value = copy.deepcopy(record)
    offset = started - value["started_at_unix"]
    value["started_at_unix"] += offset
    value["completed_at_unix"] += offset
    for phase in value["phases"]:
        phase["started_at_unix"] += offset
        phase["completed_at_unix"] += offset
    return value


