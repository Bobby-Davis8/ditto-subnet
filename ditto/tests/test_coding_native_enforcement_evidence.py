def expected_limit(source: str, container: str, language: str | None) -> int:
    """Independent restatement of the documented limit derivation."""

    spec = catalog()["resource_containers"][container]
    if source in ("nofile_limit", "log_limit_bytes"):
        return spec[source]
    policy = (
        EXECUTION_POLICY
        if spec["profile"] == "execution_profile_sha256"
        else GRADING_POLICY
    )
    if source == "scratch_limit_bytes":
        limit = policy["ScratchLimitBytes"]
        if spec["scratch"] == "executor" and language == "rust":
            return limit - min(limit // 2, 128 << 20)
        return limit
    return policy[
        {
            "memory_limit_bytes": "MemoryLimitBytes",
            "cpu_quota_millis": "CPUQuotaMillis",
            "pids_limit": "PidsLimit",
        }[source]
    ]


def observed_for(probe: dict, language: str | None) -> dict:
    expect = probe["expect"]
    kind = expect["type"]
    if kind == "outcome_in":
        return {"outcome": expect["accept"][0]}
    if kind == "exact":
        return copy.deepcopy(expect["value"])
    container = probe["id"].split(".")[0]
    if kind == "profile_equal":
        value = expected_limit(probe["bind"]["profile"], container, language)
        return {"cgroup": value, "profile": value}
    if kind == "bounded":
        value = expected_limit(probe["bind"]["limit"], container, language)
        return {"enforced": True, "limit": value, "measured": value}
    if kind == "supervisor_timeout":
        deadline = GROUP_TIMEOUTS_MS["hidden"]
        return {
            "deadline_ms": deadline,
            "elapsed_ms": deadline + deadline // 20,
            "exit_code": 124,
            "live_processes": 0,
            "test_group": "hidden",
        }
    if kind == "control":
        suite = digest(f"{language}-control-suite")
        passed, timed_out = {
            "all_pass": (3, False),
            "some_fail": (1, False),
            "timeout": (0, True),
        }[expect["result"]]
        return {
            "passed": passed,
            "suite_sha256": suite,
            "timed_out": timed_out,
            "total": 3,
        }
    assert kind == "subordinate_ids"
    return {
        "host_gid": SUBORDINATE["gid_start"] + expect["gid"] - 1,
        "host_uid": SUBORDINATE["uid_start"] + expect["uid"] - 1,
    }


def build_record(
    kind: str, *, tools: dict, pre_sha: str, started: int, inputs: dict | None = None
) -> dict:
    entry = catalog()["kinds"][kind]
    endpoints = ENDPOINTS if kind == "network_enforcement" else []
    phases = []
    moment = started
    for phase in entry["phases"]:
        probes = []
        for probe in entry["probes"]:
            if probe["phase"] != phase:
                continue
            scopes: list[tuple[str | None, str | None]]
            if probe["scope"] == "host":
                scopes = [(None, None)]
            elif probe["scope"] == "language":
                scopes = [(language, None) for language in EVIDENCE.LANGUAGES]
            else:
                scopes = [(None, endpoint) for endpoint in TRUSTED]
            for language, endpoint in scopes:
                probes.append(
                    {
                        "id": probe["id"],
                        "language": language,
                        "endpoint_sha256": endpoint,
                        "expect": copy.deepcopy(probe["expect"]),
                        "observed": observed_for(probe, language),
                        "matched": True,
                    }
                )
        probes.sort(
            key=lambda item: (
                item["id"],
                item["language"] or "",
                item["endpoint_sha256"] or "",
            )
        )
        phases.append(
            {
                "name": phase,
                "started_at_unix": moment + 1,
                "completed_at_unix": moment + 2,
                "probes": probes,
            }
        )
        moment += 2
    return {
        "schema": EVIDENCE.RECORD_SCHEMA,
        "kind": kind,
        "coverage": "same_boot",
        "not_covered": ["daemon_restart_recovery", "reboot_recovery"],
        "tolerances_version": EVIDENCE.TOLERANCES["version"],
        "host": {
            "machine_id_sha256": MACHINE,
            "boot_id": BOOT,
            "kernel_release": KERNEL,
            "daemon_identity_sha256": DAEMON,
            "subordinate_ids": dict(SUBORDINATE),
            "router_namespace": "rootless-netns",
        },
        "release": {
            "source_revision": REVISION,
            "release_manifest_sha256": MANIFEST,
            "runtime_archive_sha256": RUNTIME,
            "image_approval_sha256": dict(IMAGES),
        },
        "pre_collection_preflight_sha256": pre_sha,
        "inputs": {name: (inputs or INPUTS)[name] for name in entry["inputs"]},
        "endpoints": copy.deepcopy(endpoints),
        "tools": dict(tools),
        "preconditions": dict(EVIDENCE.PRECONDITIONS),
        "phases": phases,
        "residue": dict(EVIDENCE.RESIDUE),
        "started_at_unix": started,
        "completed_at_unix": moment + 1,
    }


