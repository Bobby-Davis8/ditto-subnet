def test_store_refusals(world, monkeypatch, case, reason):
    path = world.store
    uid = os.getuid()
    if case == "group readable":
        world.store.chmod(0o750)
    elif case == "world readable":
        world.store.chmod(0o755)
    elif case == "other owner":
        monkeypatch.setattr(EVIDENCE, "_protected_ancestors", lambda *_args: None)
