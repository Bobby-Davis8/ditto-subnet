def openssl_3() -> str | None:
    path = shutil.which("openssl")
    if path is None:
        return None
    path = str(Path(path).resolve())
    version = subprocess.run([path, "version"], capture_output=True, check=False)
    return path if version.stdout.startswith(b"OpenSSL 3.") else None


OPENSSL = openssl_3()
if OPENSSL is None and os.environ.get("CI"):
    raise RuntimeError("CI must provide OpenSSL 3 for curator signature tests")
needs_openssl = pytest.mark.skipif(OPENSSL is None, reason="OpenSSL 3 is unavailable")
# Only used by tests that skip when OpenSSL 3 is unavailable.
OPENSSL_BIN = OPENSSL or "/usr/bin/openssl"


class Curator:
    def __init__(self, directory: Path, name: str) -> None:
        directory.mkdir(parents=True, exist_ok=True)
        self.private = directory / f"{name}.key"
        self.public = directory / f"{name}.pem"
        subprocess.run(
            [
                OPENSSL_BIN,
                "genpkey",
                "-algorithm",
                "ed25519",
                "-out",
                str(self.private),
            ],
            check=True,
            capture_output=True,
        )
        subprocess.run(
            [
                OPENSSL_BIN,
                "pkey",
                "-in",
                str(self.private),
                "-pubout",
                "-out",
                str(self.public),
            ],
            check=True,
            capture_output=True,
        )
        der = base64.b64decode(b"".join(self.public.read_bytes().splitlines()[1:-1]))
        self.key_sha256 = hashlib.sha256(der[12:]).hexdigest()

    def sign(self, raw: bytes, path: Path) -> Path:
        message = path.with_suffix(".message")
        message.write_bytes(raw)
        subprocess.run(
            [
                OPENSSL_BIN,
                "pkeyutl",
                "-sign",
                "-inkey",
                str(self.private),
                "-rawin",
                "-in",
                str(message),
                "-out",
                str(path),
            ],
            check=True,
            capture_output=True,
        )
        return path


def approval_value(review_value: dict, **overrides) -> dict:
    value = {
        "schema": EVIDENCE.APPROVAL_SCHEMA,
        "purpose": "private-compatibility-once",
        "source_revision": REVISION,
        "release_manifest_sha256": MANIFEST,
        "plan_sha256": digest("plan"),
        "helper_sha256": digest("helper"),
        "runner_sha256": hashlib.sha256(
            (ROOT / EVIDENCE.NATIVE_RUNNER_FILE).read_bytes()
        ).hexdigest(),
        "binding_sha256": hashlib.sha256(
            (ROOT / EVIDENCE.NATIVE_BINDING_FILE).read_bytes()
        ).hexdigest(),
        "machine_id_sha256": MACHINE,
        "boot_id": BOOT,
        "issued_at_unix": T0 + 4200,
        "expires_at_unix": T0 + 4200 + 3600,
        "controls": 16,
        "max_jobs": 2,
        "images": {
            language: {
                "image_ref": f"coding-runtime.invalid/{language}/runtime@sha256:"
                + digest(language + "-manifest"),
                "config_digest": "sha256:" + digest(language + "-config"),
                "approval_sha256": IMAGES[language],
                "driver_profile": NATIVE.PROFILES[language],
            }
            for language in EVIDENCE.LANGUAGES
        },
        "evidence_sha256": dict(review_value.get("evidence_sha256", {})),
        "shadow_only": True,
        "weight_eligible": False,
    }
    value.update(overrides)
    return value


class Approval:
    def __init__(self, world: World) -> None:
        self.world = world
        self.directory = world.tmp / "curator"
        self.curator = Curator(self.directory, "curator")
        review_value, ok = world.review()
        assert ok
        self.review_value = review_value
        self.review = self.directory / "review.json"
        self.review.write_bytes(canonical(review_value))
        self.value = approval_value(review_value)

    def write(self, value=None, *, signer=None) -> tuple[Path, Path]:
        body = (
            json.dumps(value or self.value, indent=2, sort_keys=True).encode() + b"\n"
        )
        approval = self.directory / "approval.json"
        approval.write_bytes(body)
        signature = (signer or self.curator).sign(body, self.directory / "approval.sig")
        return approval, signature

    def check(
        self,
        *,
        approval=None,
        signature=None,
        review=None,
        public=None,
        pins=None,
        openssl=None,
    ):
        if approval is None or signature is None:
            approval, signature = self.write()
        store, checkout = self.world.open()
        with store:
            return EVIDENCE.check_approval(
                store=store,
                checkout=checkout,
                profiles=self.world.profiles(),
                profile_pins=dict(INPUTS) if pins is None else pins,
                review_raw=(review or self.review).read_bytes(),
                approval_raw=approval.read_bytes(),
                signature=signature.read_bytes(),
                public_key_raw=(public or self.curator.public).read_bytes(),
                curator_signing_key_sha256=self.curator.key_sha256,
                openssl=Path(openssl or OPENSSL_BIN),
            )

    def arguments(self, approval: Path, signature: Path) -> list[str]:
        arguments = [
            "check-approval",
            "--store",
            str(self.world.store),
            "--checkout",
            str(self.world.checkout),
            "--review",
            str(self.review),
            "--approval",
            str(approval),
            "--signature",
            str(signature),
            "--curator-public-key",
            str(self.curator.public),
            "--curator-signing-key-sha256",
            self.curator.key_sha256,
            "--openssl",
            OPENSSL_BIN,
            *self.world.profile_arguments(),
        ]
        for name, value in INPUTS.items():
            arguments += ["--" + name.replace("_", "-"), value]
        return arguments


