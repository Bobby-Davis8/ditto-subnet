def stdout_bytes(value: dict) -> bytes:
    return (json.dumps(value, sort_keys=True) + "\n").encode()


def canonical(value) -> bytes:
    return EVIDENCE.canonical_bytes(value)


def find_probe(record: dict, probe_id: str, language=None, endpoint=None) -> dict:
    for phase in record["phases"]:
        for probe in phase["probes"]:
            if (probe["id"], probe["language"], probe["endpoint_sha256"]) == (
                probe_id,
                language,
                endpoint,
            ):
                return probe
    raise AssertionError(probe_id)


def keys_of(value) -> set[str]:
    if isinstance(value, dict):
        return set(value) | {key for item in value.values() for key in keys_of(item)}
    if isinstance(value, list):
        return {key for item in value for key in keys_of(item)}
    return set()


